function pick(arr: string[]): string {
  return arr[randomInt(arr.length)];
}

export function generateSwapId(): string {
  const digits = randomInt(1000, 9999);
  return `${pick(adjectives)}-${pick(cryptoDescriptors)}-${digits}`;
}
